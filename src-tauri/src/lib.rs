/// Where the generated TypeScript bindings live, relative to this crate.
pub const BINDINGS_PATH: &str = "../src/api/bindings.ts";

/// Registry of every command and event, used both to wire the IPC handler
/// and to generate the TypeScript bindings.
pub fn specta_builder() -> Builder<tauri::Wry> {
    use commands::*;
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            // repository
            repository::open_repository,
            repository::init_repository,
            repository::clone_repository,
            repository::suggest_clone_folder,
            repository::close_repository,
            repository::get_repo_info,
            repository::list_recent_repos,
            repository::remove_recent_repo,
            repository::cancel_operation,
            repository::take_launch_path,
            // graph
            graph::get_graph_info,
            graph::get_graph_rows,
            graph::search_commits,
            graph::locate_commit,
            // commits & history
            commit::get_commit_detail,
            commit::get_commit_file_diff,
            commit::get_file_history,
            commit::get_blame,
            commit::get_head_message,
            commit::create_commit,
            commit::reset_to,
            commit::undo,
            // staging & conflicts
            staging::get_status,
            staging::get_working_diff,
            staging::stage_files,
            staging::unstage_files,
            staging::stage_all,
            staging::unstage_all,
            staging::discard_files,
            staging::discard_all,
            staging::stage_hunk,
            staging::unstage_hunk,
            staging::discard_hunk,
            staging::resolve_conflict,
            staging::mark_resolved,
            staging::abort_operation,
            staging::continue_operation,
            // branches
            branch::list_branches,
            branch::create_branch,
            branch::checkout_branch,
            branch::checkout_remote_branch,
            branch::checkout_commit,
            branch::rename_branch,
            branch::delete_branch,
            branch::merge_branch,
            // remotes
            remote::list_remotes,
            remote::fetch,
            remote::pull,
            remote::push,
            remote::delete_remote_branch,
            remote::push_tag,
            remote::delete_remote_tag,
            // stash
            stash::list_stashes,
            stash::stash_save,
            stash::stash_apply,
            stash::stash_pop,
            stash::stash_drop,
            // tags
            tag::list_tags,
            tag::create_tag,
            tag::delete_tag,
            // system
            system::get_git_version,
            system::open_in_editor,
            system::reveal_in_file_manager,
        ])
        .events(collect_events![events::RepoChanged])
}

/// Writes the TypeScript bindings for the current commands and types.
pub fn export_bindings(builder: &Builder<tauri::Wry>, path: &str) {
    use specta_typescript::{BigIntExportBehavior, Typescript};
    builder
        .export(
            Typescript::default()
                .bigint(BigIntExportBehavior::Number)
                .header("// Generated by tauri-specta from the Rust types. Do not edit.\n/* eslint-disable */\n// @ts-nocheck"),
            path,
        )
        .expect("failed to export TypeScript bindings");
}

/// A repository folder given as the first command-line argument
/// (`branchly ~/code/project`), made absolute.
fn launch_path() -> Option<String> {
    let arg = std::env::args_os().nth(1)?;
    let path = std::path::PathBuf::from(arg);
    let path = if path.is_absolute() {
        path
    } else {
        std::env::current_dir().ok()?.join(path)
    };
    Some(path.to_string_lossy().into_owned())
}

/// Name under which the desktop identifies the app on Linux: the Wayland
/// app_id and the X11 `WM_CLASS`. It must match the installed launcher
/// (`Branchly.desktop`, `StartupWMClass=Branchly`) so the taskbar shows the
/// app icon and groups the window with the pinned launcher.
#[cfg(target_os = "linux")]
const PROGRAM_NAME: &str = "Branchly";

pub fn run() {
    #[cfg(target_os = "linux")]
    glib::set_prgname(Some(PROGRAM_NAME));

    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder, BINDINGS_PATH);

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let data_dir = app.path().app_data_dir()?;
            app.manage(AppState::new(
                RecentStore::new(data_dir.join("recent.json")),
                launch_path(),
            ));
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running Branchly");
}

